using UpInBlue.Leonardo.Tokens.Model;

namespace UpInBlue.Leonardo.Tokens.Generation;

/// <summary>
/// Generates the static class <c>LeonardoTokens</c> with the token values for code, for WinUI 3 and WPF.
/// </summary>
internal static class CSharpGenerator
{
    public const string WinUIPath = "src/UpInBlue.Leonardo.WinUI/Generated/LeonardoTokens.g.cs";
    public const string WpfPath = "src/UpInBlue.Leonardo.Wpf/Generated/LeonardoTokens.g.cs";

    public static GeneratedFile WinUI(TokenCatalog catalog) => Generate(catalog, WinUIPath, new Platform(
        Namespace: "UpInBlue.Leonardo.WinUI",
        Usings: ["System.Numerics", "Windows.UI"],
        Color: color => $"Microsoft.UI.ColorHelper.FromArgb(0x{color.A:X2}, 0x{color.R:X2}, 0x{color.G:X2}, 0x{color.B:X2})",
        PointType: "Vector2",
        Point: (x, y) => $"new({Text.Float(x)}, {Text.Float(y)})",
        PointDescription: "Composition easing, for example <c>Compositor.CreateCubicBezierEasingFunction</c>"));

    public static GeneratedFile Wpf(TokenCatalog catalog) => Generate(catalog, WpfPath, new Platform(
        Namespace: "UpInBlue.Leonardo.Wpf",
        Usings: ["System.Windows", "System.Windows.Media"],
        Color: color => $"Color.FromArgb(0x{color.A:X2}, 0x{color.R:X2}, 0x{color.G:X2}, 0x{color.B:X2})",
        PointType: "Point",
        Point: (x, y) => $"new({Text.Double(x)}, {Text.Double(y)})",
        PointDescription: "a <c>KeySpline</c>"));

    private static GeneratedFile Generate(TokenCatalog catalog, string path, Platform platform)
    {
        var writer = new CodeWriter();
        writer.Line($"// {Text.Header}");
        writer.Line("// <auto-generated />");
        writer.Line("#nullable enable");
        writer.Line();
        foreach (var @using in platform.Usings)
        {
            writer.Line($"using {@using};");
        }

        writer.Line();
        writer.Line($"namespace {platform.Namespace};");
        writer.Line();
        Summary(writer, "The values of the Leonardo design tokens for code. In XAML, use the <c>Leonardo…</c> resources instead.");
        writer.Line("public static class LeonardoTokens");
        writer.Line("{").Indent();

        Class(writer, "Palette", catalog.Tokens.GroupDescription("palette") ?? "The blue scale.", () =>
        {
            foreach (var token in catalog.Palette)
            {
                Member(writer, token, $"public static readonly Color {Text.Pascal(token.Name)} = {platform.Color(token.Color)};");
            }
        });

        Class(writer, "Light", "Theme colors for light mode. In high contrast, use system colors instead.", () =>
        {
            foreach (var token in catalog.LightFor(OutputPlatform.Windows))
            {
                Member(writer, token, $"public static readonly Color {Text.Pascal(token.Name)} = {platform.Color(token.Color)};");
            }
        });

        Class(writer, "Dark", "Theme colors for dark mode. In high contrast, use system colors instead.", () =>
        {
            foreach (var token in catalog.DarkFor(OutputPlatform.Windows))
            {
                Member(writer, token, $"public static readonly Color {Text.Pascal(token.Name)} = {platform.Color(token.Color)};");
            }
        });

        Class(writer, "Space", "Spacing in epx. " + (catalog.Tokens.GroupDescription("space") ?? string.Empty), () =>
        {
            foreach (var token in catalog.Space)
            {
                Member(writer, token, $"public const double {Text.Pascal(token.Name)} = {Text.Double(token.Dimension.Value)};");
            }
        });

        Class(writer, "Radius", "Corner radii in epx. " + (catalog.Tokens.GroupDescription("radius") ?? string.Empty), () =>
        {
            foreach (var token in catalog.Radius)
            {
                Member(writer, token, $"public const double {Text.Pascal(token.Name)} = {Text.Double(token.Dimension.Value)};");
            }
        });

        Class(writer, "Density", "List row heights in epx. " + (catalog.Tokens.GroupDescription("density") ?? string.Empty), () =>
        {
            foreach (var token in catalog.Density)
            {
                Member(writer, token, $"public const double {Text.Pascal(token.Name)} = {Text.Double(token.Dimension.Value)};");
            }
        });

        Class(writer, "Size", "Sizes in epx. " + (catalog.Tokens.GroupDescription("size") ?? string.Empty), () =>
        {
            foreach (var token in catalog.SizeFor(OutputPlatform.Windows))
            {
                Member(writer, token, $"public const double {Text.Pascal(token.Name)} = {Text.Double(token.Dimension.Value)};");
            }
        });

        Class(writer, "Typography", "The type roles on Windows. Sizes in epx.", () =>
        {
            var first = true;
            foreach (var role in catalog.TypeRoles)
            {
                if (role.Windows is not { } style)
                {
                    continue;
                }

                if (!first)
                {
                    writer.Line();
                }

                first = false;
                Summary(writer, $"The {role.Name} role. Token: <c>typography.{role.Name}.windows</c>.");
                writer.Line($"public static class {Text.Pascal(role.Name)}");
                writer.Line("{").Indent();
                Summary(writer, "The font family.");
                writer.Line($"public const string FontFamily = {Text.StringLiteral(style.FontFamily)};");
                writer.Line();
                Summary(writer, "The font size in epx.");
                writer.Line($"public const double FontSize = {Text.Double(style.FontSize)};");
                writer.Line();
                Summary(writer, "The line height in epx.");
                writer.Line($"public const double LineHeight = {Text.Double(style.LineHeight)};");
                writer.Line();
                Summary(writer, $"The font weight ({Text.FontWeightName(style.FontWeight)}).");
                writer.Line($"public const ushort FontWeight = {style.FontWeight};");
                if (style.Color is { } color)
                {
                    writer.Line();
                    Summary(writer, "The resource key of the brush for the text color.");
                    writer.Line($"public const string ForegroundBrushKey = {Text.StringLiteral(XamlGenerator.BrushKey(color))};");
                }

                writer.Outdent().Line("}");
            }
        });

        Class(writer, "Motion", catalog.Tokens.GroupDescription("motion") ?? "Motion values.", () =>
        {
            var first = true;
            foreach (var motion in catalog.Motion)
            {
                if (!first)
                {
                    writer.Line();
                }

                first = false;
                var token = motion.Token;
                var name = XamlGenerator.MotionName(motion);
                switch (token.Type)
                {
                    case TokenType.CubicBezier:
                        var curve = token.CubicBezier;
                        Summary(writer, Describe(token, $"First control point of the curve, for {platform.PointDescription}."));
                        writer.Line($"public static readonly {platform.PointType} {name}ControlPoint1 = {platform.Point(curve.X1, curve.Y1)};");
                        writer.Line();
                        Summary(writer, Describe(token, $"Second control point of the curve, for {platform.PointDescription}."));
                        writer.Line($"public static readonly {platform.PointType} {name}ControlPoint2 = {platform.Point(curve.X2, curve.Y2)};");
                        break;
                    case TokenType.Duration:
                        Member(writer, token, $"public static readonly TimeSpan {name} = TimeSpan.FromMilliseconds({Text.Double(token.Duration.Milliseconds)});");
                        break;
                    case TokenType.Dimension:
                        Member(writer, token, $"public const double {name} = {Text.Double(token.Dimension.Value)};", "In epx.");
                        break;
                    case TokenType.Number when Text.IsWhole(token.Number):
                        Member(writer, token, $"public const int {name} = {Text.Number(token.Number)};");
                        break;
                    case TokenType.Number:
                        Member(writer, token, $"public const double {name} = {Text.Double(token.Number)};");
                        break;
                    default:
                        throw new TokenException($"Motion token '{token.Path}' has the unsupported type {token.Type}.");
                }
            }
        }, last: true);

        writer.Outdent().Line("}");
        return GeneratedFile.FromText(path, writer.ToString());
    }

    private static void Class(CodeWriter writer, string name, string description, Action body, bool last = false)
    {
        Summary(writer, Text.Xml(description.Trim()));
        writer.Line($"public static class {name}");
        writer.Line("{").Indent();
        body();
        writer.Outdent().Line("}");
        if (!last)
        {
            writer.Line();
        }
    }

    private static void Member(CodeWriter writer, Token token, string declaration, string? note = null)
    {
        Summary(writer, Describe(token, note));
        writer.Line(declaration);
    }

    private static string Describe(Token token, string? note)
    {
        var parts = new List<string>();
        if (note is not null)
        {
            parts.Add(note);
        }

        if (token.Description is { } description)
        {
            parts.Add(Text.Xml(description));
        }

        parts.Add($"Token: <c>{token.Path}</c>.");
        if (token.IsProposal)
        {
            parts.Add("Proposal, not final yet.");
        }

        return string.Join(" ", parts);
    }

    private static void Summary(CodeWriter writer, string text)
    {
        writer.Line("/// <summary>");
        writer.Line($"/// {text}");
        writer.Line("/// </summary>");
    }

    private sealed record Platform(
        string Namespace,
        string[] Usings,
        Func<RgbColor, string> Color,
        string PointType,
        Func<double, double, string> Point,
        string PointDescription);
}
