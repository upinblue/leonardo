using System.Globalization;
using System.Text;

namespace UpInBlue.Leonardo.Tokens.Generation;

/// <summary>
/// Naming and formatting helpers shared by all generators. All output is culture-invariant.
/// </summary>
internal static class Text
{
    public const string Header = "Generated by UpInBlue.Leonardo.Tokens from tokens/leonardo.tokens.json. Do not edit.";

    /// <summary>
    /// <c>textPrimary</c> → <c>TextPrimary</c>. Names of up to two letters become uppercase: <c>xs</c> → <c>XS</c>, <c>m</c> → <c>M</c>.
    /// </summary>
    public static string Pascal(string name)
        => name.Length <= 2
            ? name.ToUpperInvariant()
            : char.ToUpperInvariant(name[0]) + name[1..];

    /// <summary>
    /// <c>textPrimary</c> → <c>text-primary</c>.
    /// </summary>
    public static string Kebab(string name)
    {
        var builder = new StringBuilder(name.Length + 4);
        foreach (var character in name)
        {
            if (char.IsUpper(character))
            {
                if (builder.Length > 0)
                {
                    builder.Append('-');
                }

                builder.Append(char.ToLowerInvariant(character));
            }
            else
            {
                builder.Append(character);
            }
        }

        return builder.ToString();
    }

    /// <summary>
    /// The shortest round-trip representation of a number, with a period as decimal separator.
    /// </summary>
    public static string Number(double value) => value.ToString(CultureInfo.InvariantCulture);

    /// <summary>
    /// A number as a C# <see cref="float"/> literal, for example <c>0.55f</c>.
    /// </summary>
    public static string Float(double value) => ((float)value).ToString(CultureInfo.InvariantCulture) + "f";

    /// <summary>
    /// A number as a C# literal of type <see cref="double"/>, for example <c>16d</c>.
    /// </summary>
    public static string Double(double value) => Number(value) + "d";

    /// <summary>
    /// Whether a number has no fractional part.
    /// </summary>
    public static bool IsWhole(double value) => value == Math.Floor(value) && Math.Abs(value) <= int.MaxValue;

    /// <summary>
    /// Escapes text for XML content, attributes and documentation comments.
    /// </summary>
    public static string Xml(string text)
        => text.Replace("&", "&amp;", StringComparison.Ordinal)
            .Replace("<", "&lt;", StringComparison.Ordinal)
            .Replace(">", "&gt;", StringComparison.Ordinal)
            .Replace("\"", "&quot;", StringComparison.Ordinal);

    /// <summary>
    /// Makes text safe inside an XML comment, which must not contain two hyphens in a row.
    /// </summary>
    public static string XmlComment(string text) => text.Replace("--", "- -", StringComparison.Ordinal);

    /// <summary>
    /// Escapes text for a C# or Swift string literal.
    /// </summary>
    public static string StringLiteral(string text)
        => "\"" + text.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal) + "\"";

    /// <summary>
    /// Escapes text for a Markdown table cell.
    /// </summary>
    public static string MarkdownCell(string text) => text.Replace("|", "\\|", StringComparison.Ordinal);

    /// <summary>
    /// The common name of a font weight, for example 350 → Semilight.
    /// </summary>
    public static string FontWeightName(int weight) => weight switch
    {
        100 => "Thin",
        200 => "Extra light",
        300 => "Light",
        350 => "Semilight",
        400 => "Regular",
        500 => "Medium",
        600 => "Semibold",
        700 => "Bold",
        800 => "Extra bold",
        900 => "Black",
        _ => Number(weight),
    };
}

/// <summary>
/// Builds a text file line by line with <c>\n</c> line endings and four-space indentation.
/// </summary>
internal sealed class CodeWriter
{
    private readonly StringBuilder _builder = new();
    private int _indent;

    public CodeWriter Line(string text = "")
    {
        if (text.Length > 0)
        {
            _builder.Append(' ', _indent * 4);
            _builder.Append(text);
        }

        _builder.Append('\n');
        return this;
    }

    public CodeWriter Indent()
    {
        _indent++;
        return this;
    }

    public CodeWriter Outdent()
    {
        _indent--;
        return this;
    }

    public override string ToString() => _builder.ToString();
}
