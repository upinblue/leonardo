using System.Text.Json;

namespace UpInBlue.Leonardo.Check.Tests;

public sealed class CheckerTests
{
    private const string LiteralColorXaml = """<Border Background="#FF0000" />""";

    [Theory]
    [InlineData("src/App/Themes/Generated/Tokens.xaml")]
    [InlineData("generated/web/leonardo.css")]
    [InlineData("src/App/obj/Debug/MainPage.g.cs")]
    [InlineData("src/App/MainPage.g.i.cs")]
    [InlineData("src/App/Resources.Designer.cs")]
    [InlineData("web/node_modules/lib/styles.css")]
    [InlineData("tests/App.Tests/ContrastTests.cs")]
    [InlineData("Tests/AppTests/ViewTests.swift")]
    [InlineData("src/App/readme.md")]
    public void GeneratedBuildTestAndOtherFilesAreSkipped(string path)
        => Assert.False(LeonardoChecker.IsCandidate(path));

    [Theory]
    [InlineData("samples/UpInBlue.Leonardo.Gallery/Pages/FilesPage.xaml")]
    [InlineData("Sources/App/ContentView.swift")]
    [InlineData("web/index.html")]
    [InlineData("src/components/FileList.tsx")]
    public void UiFilesAreCandidates(string path) => Assert.True(LeonardoChecker.IsCandidate(path));

    [Theory]
    [InlineData("// Generated by UpInBlue.Leonardo.Tokens from tokens/leonardo.tokens.json. Do not edit.\nvar c = Colors.Red;")]
    [InlineData("// <auto-generated />\nvar c = Colors.Red;")]
    public void GeneratedHeadersAreSkipped(string text) => Check.Clean("src/App/Values.cs", text);

    [Fact]
    public void SuppressionWithReasonIsHonored()
        => Check.Clean("Pages/Page.xaml", """
            <!-- leonardo-check: ignore LEO001 The logo frame uses the brand color from the logo files. -->
            <Border Background="#1B6CE0" />
            """);

    [Fact]
    public void SuppressionWithoutReasonIsIgnored()
        => Check.Reports(Rules.LiteralColor, "Pages/Page.xaml", """
            <!-- leonardo-check: ignore LEO001 -->
            <Border Background="#1B6CE0" />
            """);

    [Fact]
    public void SuppressionOfAnotherRuleDoesNotApply()
        => Check.Reports(Rules.LiteralColor, "Pages/Page.xaml", """
            <Border Background="#1B6CE0" /> <!-- leonardo-check: ignore LEO002 not about font size -->
            """);

    [Fact]
    public void OutputNamesFileLineRuleAndSuggestion()
    {
        var finding = Assert.Single(Check.Run("Pages/FilesPage.xaml", "<Grid>\n" + LiteralColorXaml + "\n</Grid>"));
        var text = finding.Format();

        Assert.StartsWith("Pages/FilesPage.xaml:2: LEO001 literal-color: ", text, StringComparison.Ordinal);
        Assert.Contains("#FF0000", text, StringComparison.Ordinal);
        Assert.Contains("Suggestion: ", text, StringComparison.Ordinal);
    }

    [Fact]
    public void EveryRuleHasAUniqueIdAndName()
    {
        Assert.Equal(Rules.All.Count, Rules.All.Select(r => r.Id).Distinct().Count());
        Assert.Equal(Rules.All.Count, Rules.All.Select(r => r.Name).Distinct().Count());
    }

    [Fact]
    public void SpacingAndRadiusStepsMatchTheTokens()
    {
        using var tokens = JsonDocument.Parse(File.ReadAllText(Repository.PathOf("tokens/leonardo.tokens.json")));
        Assert.Equal(Steps(tokens.RootElement.GetProperty("space")), Vocabulary.Spacing.OrderBy(p => p.Key).Select(p => (p.Key, p.Value)));
        Assert.Equal(Steps(tokens.RootElement.GetProperty("radius")), Vocabulary.Radius.OrderBy(p => p.Key).Select(p => (p.Key, p.Value)));

        static IEnumerable<(double, string)> Steps(JsonElement group)
            => group.EnumerateObject()
                .Where(p => !p.Name.StartsWith('$'))
                .Select(p => (p.Value.GetProperty("$value").GetProperty("value").GetDouble(), p.Name.ToUpperInvariant()))
                .OrderBy(p => p.Item1)
                .ToList();
    }

    [Fact]
    public void TheLibrariesAndTheGalleryHaveNoFindings()
    {
        var findings = LeonardoChecker.CheckPaths(
            [Repository.PathOf("src/UpInBlue.Leonardo.WinUI"), Repository.PathOf("src/UpInBlue.Leonardo.Wpf"), Repository.PathOf("samples")],
            Repository.Root);

        Assert.True(findings.Count == 0, string.Join(Environment.NewLine, findings.Select(f => f.Format())));
    }
}
